-- Conference Center — Phase 1.
--
-- The Conference Center is NOT a second meetings system. It is a Zoom-first
-- view over `public.meetings` (0020), which already owns: who a meeting is
-- with, the provider, the calendar, the CRM timeline, the outcome and the
-- follow-up task. 0020 was written expecting Zoom to arrive as "a second row
-- in a check constraint and a second file in providers/". This migration is
-- that row, plus the three things that genuinely did not exist:
--
--   1. Conference categories the sales process uses (AI consultation, demos,
--      partnership meetings). Additive to meeting_type — every existing value
--      stays valid, so no row and no screen changes meaning.
--   2. An idempotency key, so a double-clicked "Schedule" or a retried
--      request can never create two Zoom meetings for one intent.
--   3. conference_settings — Zoom meeting defaults and scheduling rules,
--      one row per installation (scope), so the module is reusable for a
--      white-label client without code changes.
--
-- Zoom OAuth tokens go into the EXISTING integration_credentials table
-- (provider = 'zoom' is already allowed by its check constraint). That table
-- has RLS on and no policy: only the service role can read it. Tokens are
-- additionally encrypted by the application (AES-256-GCM) before they are
-- written, so a database dump alone does not yield a usable Zoom token.
--
-- Purely additive. No drops of data, no policy loosened, nothing renamed.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── 1. Conference categories ─────────────────────────────────────────────
alter table public.meetings drop constraint if exists meetings_meeting_type_check;
alter table public.meetings add constraint meetings_meeting_type_check
  check (meeting_type in (
    -- 0020, unchanged
    'discovery', 'demo', 'proposal_review', 'kickoff', 'strategy',
    'support', 'progress_review', 'training', 'final_review',
    'follow_up', 'custom',
    -- Conference Center
    'ai_consultation', 'ai_receptionist_demo', 'website_consultation',
    'software_demo', 'automation_review', 'partnership', 'partner_meeting'
  ));

-- ── 2. Where the meeting came from, and the idempotency key ──────────────
-- `source` lets analytics separate a booked consultation from one the admin
-- set up, without inferring it from the title. Existing rows are 'admin',
-- which is what they were.
alter table public.meetings
  add column if not exists source text not null default 'admin';

alter table public.meetings drop constraint if exists meetings_source_check;
alter table public.meetings add constraint meetings_source_check
  check (source in ('admin', 'instant', 'booking', 'partner'));

-- An instant conference is started before anyone is invited: the link is
-- copied or emailed afterwards. It is the one meeting allowed to exist
-- without a person attached, and only while it is that.
alter table public.meetings drop constraint if exists meetings_has_a_person;
alter table public.meetings add constraint meetings_has_a_person
  check (lead_id is not null or customer_id is not null
         or attendee_email is not null or source = 'instant');

-- Generated by the form when it opens. A second submit of the same form
-- collides here instead of creating a second Zoom meeting.
alter table public.meetings
  add column if not exists client_request_id uuid;

create unique index if not exists meetings_client_request_key
  on public.meetings (client_request_id)
  where client_request_id is not null;

-- Conference Center lists are "Zoom meetings, newest first".
create index if not exists meetings_provider_start_idx
  on public.meetings (provider, start_at desc);

create index if not exists meetings_source_start_idx
  on public.meetings (source, start_at desc);

-- ── 3. Non-secret facts about a connected account ────────────────────────
-- Plan type, provider user id, account id. Lives beside the token row so a
-- disconnect removes it too. Never contains a secret.
alter table public.integration_credentials
  add column if not exists metadata jsonb not null default '{}'::jsonb;

-- ── 4. conference_settings ───────────────────────────────────────────────
create table if not exists public.conference_settings (
  id                         uuid primary key default gen_random_uuid(),
  -- One row per installation. 'default' for Tomorrow's Tech AI; a white-label
  -- deployment gets its own database and its own 'default' row.
  scope                      text not null unique default 'default',

  brand_name                 text not null default 'Tomorrow''s Tech AI',
  default_timezone           text not null default 'America/Chicago',
  default_duration_minutes   integer not null default 30
                               check (default_duration_minutes between 5 and 480),
  instant_duration_minutes   integer not null default 60
                               check (instant_duration_minutes between 5 and 480),
  -- Minutes kept free either side of a conference when checking conflicts.
  buffer_minutes             integer not null default 0
                               check (buffer_minutes between 0 and 120),
  -- Refuse to schedule over another open meeting. On by default.
  block_conflicts            boolean not null default true,

  -- Zoom meeting defaults, sent with every create.
  zoom_waiting_room          boolean not null default true,
  zoom_join_before_host      boolean not null default false,
  zoom_mute_upon_entry       boolean not null default true,
  zoom_host_video            boolean not null default true,
  zoom_participant_video     boolean not null default false,
  -- Recording needs participant consent and a plan that supports it, so it
  -- is off unless someone deliberately turns it on.
  zoom_auto_recording        text not null default 'none'
                               check (zoom_auto_recording in ('none', 'local', 'cloud')),

  -- Send the branded invitation email (Resend) after scheduling.
  send_invites_by_email      boolean not null default true,

  updated_by                 text,
  created_at                 timestamptz not null default now(),
  updated_at                 timestamptz not null default now()
);

insert into public.conference_settings (scope)
values ('default')
on conflict (scope) do nothing;

drop trigger if exists conference_settings_touch on public.conference_settings;
create trigger conference_settings_touch
  before update on public.conference_settings
  for each row execute function public.touch_updated_at();

-- Admins only, same posture as meetings. No insert/delete from a session:
-- the row is seeded here and only ever updated.
alter table public.conference_settings enable row level security;

drop policy if exists conference_settings_admin_select on public.conference_settings;
drop policy if exists conference_settings_admin_update on public.conference_settings;

create policy conference_settings_admin_select on public.conference_settings
  for select to authenticated using (public.is_admin());
create policy conference_settings_admin_update on public.conference_settings
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

revoke all on public.conference_settings from anon;
